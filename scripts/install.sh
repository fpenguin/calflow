#!/usr/bin/env bash
# CalFlow one-line installer (v2.0).
#
# Bootstraps a CalFlow install at ~/.calflow and registers a `calflow`
# CLI shim at ~/.local/bin/calflow.
#
# Usage (after cloning the repo to a working location):
#     bash scripts/install.sh
#
# Or for a fresh machine:
#     curl -fsSL https://raw.githubusercontent.com/<you>/calflow/main/scripts/install.sh | bash
#
# What it does:
#   1. clones (or refreshes) the repo into ~/.calflow
#   2. creates a venv and installs requirements
#   3. writes ~/.local/bin/calflow shim that activates the venv and runs
#      `python -m cli.main "$@"` from the install dir
#   4. ensures ~/.local/bin is on PATH (writes to ~/.zshrc if missing)

set -euo pipefail
umask 077

REPO_URL="${CALFLOW_REPO:-https://github.com/fpenguin/calflow.git}"
INSTALL_DIR="$HOME/.calflow"

echo "🚀 Installing CalFlow..."

# --- validate existing install before staging -----------------------------
if [ -d "$INSTALL_DIR" ]; then
  if ! git -C "$INSTALL_DIR" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    echo "Existing directory is not a Git installation. Move it to a backup first."
    exit 1
  fi
  if [ -n "$(git -C "$INSTALL_DIR" status --porcelain --untracked-files=no)" ]; then
    echo "Local tracked files have changes. Commit or migrate them before upgrading."
    exit 1
  fi
  if command -v launchctl >/dev/null 2>&1; then
    for label in com.calflow com.calflow.menubar; do
      if launchctl print "gui/$(id -u)/$label" >/dev/null 2>&1; then
        echo "Stop CalFlow first: calflow stop && calflow menubar-stop"
        exit 1
      fi
    done
  fi
  echo "Existing installation found at $INSTALL_DIR. A full backup will be retained."
  read -r -p "Upgrade and preserve data? [y/N]: " confirm
  if [[ ! "$confirm" =~ ^[Yy]$ ]]; then
    echo "❌ Installation cancelled."
    exit 1
  fi
fi

# Staging and backup stay on the same filesystem. No existing files are deleted.
STAGE=$(mktemp -d "${INSTALL_DIR}.stage.XXXXXX")
BACKUP=""
PROMOTED=0
rollback() {
  local code=$?
  trap - EXIT
  if [ "$code" -ne 0 ] && [ -n "$BACKUP" ] && [ -d "$BACKUP/install" ]; then
    if [ "$PROMOTED" -eq 1 ] && [ -d "$INSTALL_DIR" ]; then
      mv "$INSTALL_DIR" "$STAGE/failed-install"
    fi
    if [ ! -e "$INSTALL_DIR" ]; then
      mv "$BACKUP/install" "$INSTALL_DIR"
      echo "Upgrade failed; previous installation restored."
    fi
  fi
  if [ "$code" -ne 0 ]; then echo "Staging files retained at $STAGE"; fi
  exit "$code"
}
trap rollback EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

echo "Fetching repository..."
git clone "$REPO_URL" "$STAGE/source"
if [ -d "$INSTALL_DIR" ]; then
  for private_dir in data secrets; do
    if [ -d "$INSTALL_DIR/$private_dir" ]; then
      mkdir -p "$STAGE/source/$private_dir"
      cp -pR "$INSTALL_DIR/$private_dir/." "$STAGE/source/$private_dir/"
    fi
  done
  BACKUP=$(mktemp -d "${INSTALL_DIR}.backup.XXXXXX")
  mv "$INSTALL_DIR" "$BACKUP/install"
fi
mv "$STAGE/source" "$INSTALL_DIR"
PROMOTED=1
cd "$INSTALL_DIR"

# --- venv + deps ----------------------------------------------------------
echo "🐍 Creating virtualenv..."
python3 -m venv .venv

echo "📦 Installing dependencies..."
.venv/bin/python -m pip install --upgrade pip
.venv/bin/python -m pip install -r requirements.txt

mkdir -p data secrets

# --- CLI shim -------------------------------------------------------------
echo "🔧 Creating CLI shim..."
mkdir -p "$HOME/.local/bin"

cat > "$HOME/.local/bin/calflow" <<EOF
#!/usr/bin/env bash
# Auto-generated by CalFlow installer.
# Use the installation's interpreter, independent of the shell environment.
cd "$INSTALL_DIR"
exec "$INSTALL_DIR/.venv/bin/python" -m cli.main "\$@"
EOF
chmod +x "$HOME/.local/bin/calflow"

if [ -n "$BACKUP" ]; then
  echo "Previous installation retained at $BACKUP/install"
fi
trap - EXIT INT TERM

# --- PATH hint ------------------------------------------------------------
if [[ ":$PATH:" != *":$HOME/.local/bin:"* ]]; then
  if [ -f "$HOME/.zshrc" ]; then
    echo 'export PATH="$HOME/.local/bin:$PATH"' >> "$HOME/.zshrc"
    echo "ℹ️  Added ~/.local/bin to PATH in ~/.zshrc"
    echo "   Reload your shell:  source ~/.zshrc"
  else
    echo "ℹ️  Add this to your shell profile so 'calflow' is on PATH:"
    echo '       export PATH="$HOME/.local/bin:$PATH"'
  fi
fi

cat <<EOF

✅ CalFlow installed at: $INSTALL_DIR

Next:
   calflow setup       # OAuth + calendar selection + daemon install
   calflow status      # check daemon
   calflow             # run one cycle now (also what launchd calls)

Interactive REPL (no daemon needed):
   cd "$INSTALL_DIR" && python3 -m cli.repl
EOF
